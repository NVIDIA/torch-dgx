// Compile CUTLASS device kernels into DGX and launch them with raw pointers
// on per-device CUDA streams.
// Match the head-dimension specializations and upper bound generated by
// PyTorch's CUDA mem_eff_attention/kernels/generate_kernels.py. Wider heads
// iterate over channel tiles rather than increasing the shared-memory footprint.
constexpr int kMaxHeadDim = 1 << 16;
template <int MaxK, bool SupportsBias, bool SupportsDropout>
using AttentionForwardKernel = PyTorchMemEffAttention::
    AttentionKernel<float, cutlass::arch::Sm80, true, MaxK <= 128 ? 64 : 32, MaxK <= 64 ? 64 : 128, MaxK, SupportsDropout, SupportsBias>;
template <int MaxK, bool SupportsDropout>
using AttentionBackwardKernel =
    PyTorchMemEffAttention::AttentionBackwardKernel<cutlass::arch::Sm80, float, true, SupportsDropout, false, 64, 64, MaxK>;

template <typename Function>
decltype(auto) dispatch_attention(int64_t head_dim, Function&& function)
{
    if (head_dim <= 64)
        return function(std::integral_constant<int, 64>{});
    if (head_dim <= 128)
        return function(std::integral_constant<int, 128>{});
    return function(std::integral_constant<int, kMaxHeadDim>{});
}

template <typename Function>
decltype(auto) dispatch_attention_dropout(int64_t head_dim, bool supports_dropout, Function&& function)
{
    return dispatch_attention(head_dim, [&](auto max_k) {
        if (supports_dropout)
            return function(max_k, std::true_type{});
        return function(max_k, std::false_type{});
    });
}

template <typename Function>
decltype(auto) dispatch_attention_forward(int64_t head_dim, bool supports_bias, bool supports_dropout, Function&& function)
{
    return dispatch_attention_dropout(head_dim, supports_dropout, [&](auto max_k, auto dropout) {
        if (supports_bias)
            return function(max_k, std::true_type{}, dropout);
        return function(max_k, std::false_type{}, dropout);
    });
}

template <typename AttentionBackward>
__global__ __launch_bounds__(
    AttentionBackward::kNumThreads,
    AttentionBackward::kMinBlocksPerSm) void attention_backward_kernel(typename AttentionBackward::Params params,
                                                                       int64_t rng_queries)
{
    const uint64_t rng_head_offset =
        (uint64_t(blockIdx.z) * params.num_heads + blockIdx.y) * rng_queries * params.num_keys;
    if (params.advance_to_block())
    {
        params.dropout_batch_head_rng_offset = rng_head_offset;
        AttentionBackward::attention_kernel(params);
    }
}

template <typename AttentionForward>
__global__ __launch_bounds__(AttentionForward::kNumThreads, AttentionForward::kMinBlocksPerSm) void attention_forward_kernel(
    typename AttentionForward::Params params, int64_t rng_queries)
{
    const uint64_t rng_head_offset =
        (uint64_t(blockIdx.z) * params.num_heads + blockIdx.y) * rng_queries * params.num_keys;
    if (params.advance_to_block())
    {
        params.dropout_batch_head_rng_offset = rng_head_offset;
        AttentionForward::attention_kernel(params);
    }
}

template <auto Kernel>
auto configure_attention_kernel(int shared_memory)
{
    static const auto kernel = [shared_memory]() -> decltype(Kernel) {
        for (const auto device : c10::irange(c10::cuda::device_count()))
        {
            int major, available_shared_memory;
            C10_CUDA_CHECK(cudaDeviceGetAttribute(&major, cudaDevAttrComputeCapabilityMajor, device));
            C10_CUDA_CHECK(
                cudaDeviceGetAttribute(&available_shared_memory, cudaDevAttrMaxSharedMemoryPerBlockOptin, device));
            if (major < 8 || available_shared_memory < shared_memory)
                return nullptr;
        }
        int current_device;
        C10_CUDA_CHECK(cudaGetDevice(&current_device));
        for (const auto device : c10::irange(c10::cuda::device_count()))
        {
            C10_CUDA_CHECK(cudaSetDevice(device));
            C10_CUDA_CHECK(cudaFuncSetAttribute(Kernel, cudaFuncAttributeMaxDynamicSharedMemorySize, shared_memory));
        }
        C10_CUDA_CHECK(cudaSetDevice(current_device));
        return Kernel;
    }();
    return kernel;
}

struct AttentionShard
{
    int64_t batch_begin, batches, head_begin, heads;
    int64_t query_begin, queries;
    int64_t key_begin = 0, keys = 0;
    int64_t partial = -1;

    int64_t offset(const Tensor& tensor, bool query_rows = false, bool bias = false) const
    {
        return batch_begin * tensor.stride(0) + head_begin * tensor.stride(1) +
               (query_rows ? query_begin : key_begin) * tensor.stride(2) + (bias ? key_begin * tensor.stride(3) : 0);
    }
};

template <typename Function>
void for_each_attention_shard(const Tensor& query, int device, Function&& function)
{
    const int64_t heads = query.size(1);
    const int64_t pairs = query.size(0) * heads;
    const int64_t pairs_per_device = pairs / c10::cuda::device_count();
    const int64_t extra_pairs = pairs % c10::cuda::device_count();
    const int64_t begin = device * pairs_per_device + std::min<int64_t>(device, extra_pairs);
    const int64_t count = pairs_per_device + (device < extra_pairs);
    int64_t current = begin;
    const int64_t end = begin + count;
    while (current < end)
    {
        const int64_t batch_begin = current / heads;
        const int64_t head_begin = current % heads;
        // Coalesce complete batches; only the two ends can be partial batches.
        const int64_t batches = head_begin == 0 && end - current >= heads ? (end - current) / heads : 1;
        const int64_t head_count = std::min(heads - head_begin, end - current);
        function(AttentionShard{ batch_begin, batches, head_begin, head_count, 0, query.size(2) });
        current += batches * head_count;
    }
}

struct AttentionPartition
{
    std::vector<std::vector<AttentionShard>> devices;
    int64_t query_slices = 1;
    int64_t key_slices = 1;
    int64_t partials = 0;

    AttentionPartition(const Tensor& query, const Tensor& key, bool is_causal, double dropout_p)
        : devices(c10::cuda::device_count())
    {
        // Keep balanced heads intact. For imbalanced heads, process all heads
        // in one launch per GPU over a slice of sequence tiles. Separate launches
        // for full and partial heads lose occupancy on small head counts.
        // CUTLASS backward cannot offset its causal diagonal for query slices.
        const int64_t tiles = ::cuda::ceil_div(query.size(2), int64_t{ 64 });
        const int64_t pairs = query.size(0) * query.size(1);
        const bool imbalanced = pairs < 2 * devices.size() && pairs % devices.size();
        // Key shards need global softmax normalization. Dropout's per-row RNG
        // indexing and causal masking assume local key coordinates in CUTLASS,
        // so those configurations keep their existing partitioning.
        if (!is_causal && dropout_p == 0.0 && imbalanced && key.size(2) >= 256)
        {
            const int64_t key_tiles = ::cuda::ceil_div(key.size(2), int64_t{ 64 });
            key_slices = std::min<int64_t>(devices.size(), key_tiles);
            partials = key_slices * query.size(0);
            for (int64_t device = 0; device < key_slices; ++device)
            {
                const int64_t begin = device * (key_tiles / key_slices) + std::min(device, key_tiles % key_slices);
                const int64_t count = key_tiles / key_slices + (device < key_tiles % key_slices);
                const int64_t key_begin = begin * 64;
                const int64_t key_end = std::min((begin + count) * 64, key.size(2));
                devices[device].push_back({ 0, query.size(0), 0, query.size(1), 0, query.size(2), key_begin,
                                            key_end - key_begin, device * query.size(0) });
            }
            return;
        }
        // Replicating every head's K/V is only worthwhile for small head counts
        // with substantial imbalance. Larger workloads retain head partitioning.
        if (!is_causal && imbalanced && query.size(2) >= 256)
            query_slices = std::min<int64_t>(devices.size(), tiles);
        if (query_slices > 1)
        {
            partials = query_slices * query.size(0);
            for (int64_t device = 0; device < query_slices; ++device)
            {
                const int64_t begin = device * (tiles / query_slices) + std::min(device, tiles % query_slices);
                const int64_t count = tiles / query_slices + (device < tiles % query_slices);
                const int64_t query_begin = begin * 64;
                const int64_t query_end = std::min((begin + count) * 64, query.size(2));
                devices[device].push_back({ 0, query.size(0), 0, query.size(1), query_begin, query_end - query_begin, 0,
                                            key.size(2), device * query.size(0) });
            }
            return;
        }
        for (const auto device : c10::irange(devices.size()))
            for_each_attention_shard(query, device, [&](AttentionShard shard) {
                shard.keys = key.size(2);
                devices[device].push_back(shard);
            });
    }
};

int64_t attention_product(int64_t a, int64_t b)
{
    TORCH_CHECK(a >= 0 && b >= 0 && (!b || a <= INT64_MAX / b), "DGX attention scratch size overflow");
    return a * b;
}

bool attention_uses_rng(double dropout_p)
{
    // CUTLASS compares FP32 probabilities. A threshold rounded to one drops
    // every element and must bypass its 1 / (1 - p) scaling.
    return dropout_p > 0.0 && static_cast<float>(dropout_p) < 1.0f;
}

at::PhiloxCudaState attention_shard_rng(
    const Tensor& query, const Tensor& key, const AttentionShard& shard, uint64_t seed, uint64_t offset)
{
    // The launch wrappers restore the full query extent for CUTLASS's per-head
    // RNG offset. Advance the base stream by this slice's first query row.
    const uint64_t first_pair = shard.batch_begin * query.size(1) + shard.head_begin;
    return at::PhiloxCudaState(seed, offset + (first_pair * query.size(2) + shard.query_begin) * key.size(2));
}

// Logical BHSD dimensions with either dense BHSD or BSHD physical storage.
// Read-only broadcast axes occupy a single physical element along that axis.
struct AttentionLayout
{
    std::array<int64_t, 4> sizes, strides;
    int64_t numel, storage_numel;

    AttentionLayout(std::array<int64_t, 4> shape, bool head_major = false, int64_t row_alignment = 1) : sizes(shape)
    {
        const auto [b, h, s, d] = sizes;
        const int64_t padded_d = ::cuda::ceil_div(d, row_alignment) * row_alignment;
        const int64_t hs = attention_product(h, s);
        const int64_t hsd = attention_product(hs, padded_d);
        numel = attention_product(attention_product(b, hs), d);
        storage_numel = attention_product(b, hsd);
        strides = head_major ? std::array<int64_t, 4>{ hsd, attention_product(s, padded_d), padded_d, 1 } :
                               std::array<int64_t, 4>{ hsd, padded_d, attention_product(h, padded_d), 1 };
        // Bias head strides are int64; Q/K/V head-major strides are bounded
        // separately by attention_input_layout.
        TORCH_CHECK(strides[2] <= INT32_MAX, "DGX attention local row strides exceed CUTLASS limits");
    }
};

AttentionLayout attention_input_layout(const Tensor& tensor,
                                       const AttentionShard& shard,
                                       bool broadcast_heads = true,
                                       bool query_rows = false)
{
    std::array<int64_t, 4> sizes{ shard.batches, shard.heads, query_rows ? shard.queries : shard.keys, tensor.size(3) };
    for (int dim = 0; dim < 3; ++dim)
        if (!tensor.stride(dim) && (dim != 1 || broadcast_heads))
            sizes[dim] = 1;
    // Preserve fused RMSNorm's contiguous heads without an extra transpose.
    const bool head_major = tensor.is_contiguous() && sizes[2] <= INT32_MAX / sizes[3];
    AttentionLayout layout(sizes, head_major);
    for (int dim = 0; dim < 3; ++dim)
        if (!tensor.stride(dim) && (dim != 1 || broadcast_heads))
            layout.strides[dim] = 0;
    return layout;
}

AttentionLayout attention_bias_layout(const Tensor& bias, const AttentionShard& shard)
{
    std::array<int64_t, 4> sizes{ shard.batches, shard.heads, shard.queries, shard.keys };
    for (int dim = 0; dim < 3; ++dim)
        if (!bias.stride(dim))
            sizes[dim] = 1;
    // CUTLASS vector loads require aligned rows even when the key length is
    // odd. Preserve broadcast batch/head/query axes without duplicating masks.
    AttentionLayout layout(sizes, true, 4);
    for (int dim = 0; dim < 3; ++dim)
        if (!bias.stride(dim))
            layout.strides[dim] = 0;
    return layout;
}

class AttentionScratch
{
public:
    explicit AttentionScratch(cudaStream_t stream) : stream_(stream)
    {
    }
    ~AttentionScratch()
    {
        if (data_)
            C10_CUDA_CHECK_WARN(cudaFreeAsync(data_, stream_));
    }
    AttentionScratch(const AttentionScratch&) = delete;
    AttentionScratch& operator=(const AttentionScratch&) = delete;

    size_t reserve(int64_t numel)
    {
        const auto bytes = static_cast<size_t>(attention_product(numel, sizeof(float)));
        TORCH_CHECK(size_ <= SIZE_MAX - 255, "DGX attention scratch size overflow");
        const auto offset = (size_ + 255) & ~size_t{ 255 };
        TORCH_CHECK(bytes <= SIZE_MAX - offset, "DGX attention scratch size overflow");
        size_ = offset + bytes;
        return offset;
    }
    void allocate()
    {
        C10_CUDA_CHECK(cudaMallocAsync(&data_, size_, stream_));
    }
    float* data(size_t offset) const
    {
        return reinterpret_cast<float*>(static_cast<uint8_t*>(data_) + offset);
    }
    void* release()
    {
        return std::exchange(data_, nullptr);
    }

private:
    cudaStream_t stream_;
    size_t size_ = 0;
    void* data_ = nullptr;
};

struct AttentionCopy
{
    __device__ void operator()(int64_t i, const float* input, float* output, StridedOffsetCalculator<2> offsets) const
    {
        const auto offset = offsets.get(i);
        output[offset[1]] = input[offset[0]];
    }
};

void copy_attention(const float* source,
                    IntArrayRef source_strides,
                    float* destination,
                    IntArrayRef destination_strides,
                    const AttentionLayout& layout,
                    cudaStream_t stream)
{
    // Coalesce dimensions that form the same contiguous span or rectangle on
    // both sides. This covers dense heads and packed-QKV sequence-major rows.
    const std::array<int, 4> order = destination_strides[1] >= destination_strides[2] ?
                                         std::array<int, 4>{ 0, 1, 2, 3 } :
                                         std::array<int, 4>{ 0, 2, 1, 3 };
    std::array<int, 4> dims{};
    int count = 0;
    for (const auto dim : order)
        if (layout.sizes[dim] > 1)
            dims[count++] = dim;
    int64_t width = 1;
    int i = count - 1;
    while (i >= 0 && source_strides[dims[i]] == width && destination_strides[dims[i]] == width)
        width *= layout.sizes[dims[i--]];
    if (i < 0)
    {
        C10_CUDA_CHECK(cudaMemcpyAsync(destination, source, width * sizeof(float), cudaMemcpyDefault, stream));
        return;
    }
    const auto source_pitch = source_strides[dims[i]];
    const auto destination_pitch = destination_strides[dims[i]];
    int64_t height = layout.sizes[dims[i--]];
    while (i >= 0 && source_strides[dims[i]] / height == source_pitch && source_strides[dims[i]] % height == 0 &&
           destination_strides[dims[i]] / height == destination_pitch && destination_strides[dims[i]] % height == 0)
        height *= layout.sizes[dims[i--]];
    // CUDA's 2-D copy pitch is bounded in bytes, while tensor strides count
    // floats. Large valid tensor strides must use the gather path instead.
    if (i < 0 && source_pitch >= width && destination_pitch >= width &&
        source_pitch <= INT32_MAX / int64_t{ sizeof(float) } && destination_pitch <= INT32_MAX / int64_t{ sizeof(float) })
    {
        C10_CUDA_CHECK(cudaMemcpy2DAsync(destination, destination_pitch * sizeof(float), source,
                                         source_pitch * sizeof(float), width * sizeof(float), height, cudaMemcpyDefault,
                                         stream));
        return;
    }
    const auto offsets = make_strided_offset_calculator<2>(
        layout.sizes, std::array<IntArrayRef, 2>{ source_strides, destination_strides });
    const auto blocks =
        static_cast<unsigned int>(std::min<int64_t>(::cuda::ceil_div(layout.numel, int64_t{ kNumThreads }), 65535));
    lambda_kernel<<<blocks, kNumThreads, 0, stream>>>(layout.numel, AttentionCopy(), source, destination, offsets);
    C10_CUDA_KERNEL_LAUNCH_CHECK();
}

struct AttentionBuffer
{
    AttentionLayout layout;
    size_t offset;
    float* external = nullptr;

    AttentionBuffer(AttentionScratch& scratch, AttentionLayout layout_, int64_t minimum_numel = 0)
        : layout(layout_), offset(scratch.reserve(std::max(layout.storage_numel, minimum_numel)))
    {
    }
    AttentionBuffer(AttentionLayout layout_, float* data) : layout(layout_), offset(0), external(data)
    {
    }

    float* data(const AttentionScratch& scratch) const
    {
        return external ? external : scratch.data(offset);
    }

    void copy_from(const AttentionScratch& scratch,
                   const Tensor& source,
                   const AttentionShard& shard,
                   cudaStream_t stream,
                   bool query_rows = false,
                   bool bias = false) const
    {
        copy_attention(source.const_data_ptr<float>() + shard.offset(source, query_rows, bias), source.strides(),
                       data(scratch), layout.strides, layout, stream);
    }
    void copy_to(const AttentionScratch& scratch,
                 Tensor& destination,
                 const AttentionShard& shard,
                 cudaStream_t stream,
                 bool query_rows = false,
                 bool bias = false) const
    {
        copy_attention(data(scratch), layout.strides,
                       destination.data_ptr<float>() + shard.offset(destination, query_rows, bias),
                       destination.strides(), layout, stream);
    }
};

struct AttentionPartialSum
{
    __device__ void operator()(int64_t i, const float* input, float* output, int64_t partial_stride, int64_t count) const
    {
        float sum = 0.0f;
        for (int64_t part = 0; part < count; ++part)
            sum += input[part * partial_stride + i];
        output[i] = sum;
    }
};

void reduce_attention_partials(const AttentionPartition& partition, const Tensor& partials, Tensor& gradient)
{
    if (!partials.defined())
        return;
    // Partials and gradients both have dense BSHD storage. Partition the
    // physical output so peers write disjoint spans rather than interleaved heads.
    // Enqueue independent dK/dV reductions together; the caller joins once.
    parallel_for_each_async([&](int device, cudaStream_t stream) {
        const auto [begin, count] = aligned_chunk(1, gradient.numel(), device);
        if (!count)
            return;
        const auto blocks =
            static_cast<unsigned int>(std::min<int64_t>(::cuda::ceil_div(count, size_t{ kNumThreads }), 65535));
        offset_lambda_kernel<<<blocks, kNumThreads, 0, stream>>>(
            count, begin, AttentionPartialSum(), partials.const_data_ptr<float>(), gradient.data_ptr<float>(),
            gradient.numel(), partition.query_slices);
        C10_CUDA_KERNEL_LAUNCH_CHECK();
    });
}

void copy_attention_lse(float* local,
                        const Tensor& global,
                        const AttentionShard& shard,
                        int64_t local_rows,
                        bool to_global,
                        cudaStream_t stream)
{
    const AttentionLayout layout({ shard.batches, shard.heads, local_rows, 1 }, true);
    const std::array<int64_t, 4> global_strides{ global.stride(0), global.stride(1), 1, 1 };
    auto* global_data = global.data_ptr<float>() + shard.offset(global, true);
    if (to_global)
        copy_attention(local, layout.strides, global_data, global_strides, layout, stream);
    else
        copy_attention(global_data, global_strides, local, layout.strides, layout, stream);
}

__global__ void attention_mask_lse_kernel(
    int64_t rows, int64_t keys, const float* bias, float* lse, StridedOffsetCalculator<2> offsets)
{
    const int lane = threadIdx.x % 32;
    for (int64_t row = int64_t(blockIdx.x) * (blockDim.x / 32) + threadIdx.x / 32; row < rows;
         row += int64_t(gridDim.x) * (blockDim.x / 32))
    {
        const auto offset = offsets.get(row);
        bool any_key = false;
        for (int64_t column = 0; column < keys && !any_key; column += 32)
            any_key = __any_sync(0xffffffff, column + lane < keys && bias[offset[0] + column + lane] != -CUDART_INF_F);
        // CUTLASS saves zero for fully masked rows. Such a shard has zero
        // softmax mass, so its internal merge statistic must instead be -inf.
        if (!lane && !any_key)
            lse[offset[1]] = -CUDART_INF_F;
    }
}

__global__ void attention_merge_kernel(int64_t row_begin,
                                       int64_t rows,
                                       int64_t queries,
                                       int64_t heads,
                                       int64_t channels,
                                       int64_t lse_rows,
                                       int64_t output_stride,
                                       int64_t lse_stride,
                                       int64_t parts,
                                       const float* partial_output,
                                       const float* partial_lse,
                                       float* output,
                                       float* lse)
{
    extern __shared__ float weights[];
    const int lane = threadIdx.x % 32;
    auto* row_weights = weights + (threadIdx.x / 32) * parts;
    for (int64_t index = int64_t(blockIdx.x) * (blockDim.x / 32) + threadIdx.x / 32; index < rows;
         index += int64_t(gridDim.x) * (blockDim.x / 32))
    {
        // Walk BSH rows so each device publishes contiguous output spans.
        const int64_t row = row_begin + index;
        const int64_t head = row % heads;
        const int64_t query = row / heads % lse_rows;
        const int64_t batch = row / (heads * lse_rows);
        const int64_t lse_index = (batch * heads + head) * lse_rows + query;
        if (query >= queries)
        {
            if (!lane && lse)
                lse[lse_index] = CUDART_INF_F;
            continue;
        }
        if (!lane)
        {
            float maximum = -CUDART_INF_F;
            bool has_nan = false;
            for (int64_t part = 0; part < parts; ++part)
            {
                const float value = partial_lse[part * lse_stride + lse_index];
                maximum = fmaxf(maximum, value);
                has_nan |= ::isnan(value);
            }
            if (has_nan)
                maximum = CUDART_NAN_F;
            float sum = 0.0f;
            for (int64_t part = 0; part < parts; ++part)
            {
                const float value = partial_lse[part * lse_stride + lse_index];
                const float weight = maximum == -CUDART_INF_F ? 0.0f : expf(value - maximum);
                row_weights[part] = weight;
                sum += weight;
            }
            for (int64_t part = 0; part < parts; ++part)
                row_weights[part] /= sum == 0.0f ? 1.0f : sum;
            // Preserve CUTLASS's saved-LSE convention for globally masked rows.
            if (lse)
                lse[lse_index] = sum == 0.0f ? 0.0f : maximum + logf(sum);
        }
        __syncwarp();
        const int64_t output_index = ((batch * queries + query) * heads + head) * channels;
        for (int64_t channel = lane; channel < channels; channel += 32)
        {
            float sum = 0.0f;
            for (int64_t part = 0; part < parts; ++part)
                if (row_weights[part] != 0.0f)
                    sum += row_weights[part] * partial_output[part * output_stride + output_index + channel];
            output[output_index + channel] = sum;
        }
        __syncwarp();
    }
}

void merge_attention_partials(const AttentionPartition& partition,
                              const Tensor& partial_output,
                              const Tensor& partial_lse,
                              Tensor& output,
                              Tensor& lse)
{
    const int64_t lse_rows = partial_lse.size(2);
    const int64_t rows = output.size(0) * output.size(1) * lse_rows;
    parallel_for_each([&](int device, cudaStream_t stream) {
        const auto [begin, count] = aligned_chunk(1, rows, device);
        if (!count)
            return;
        const auto blocks =
            static_cast<unsigned int>(std::min<int64_t>(::cuda::ceil_div(count, int64_t{ kNumThreads / 32 }), 65535));
        attention_merge_kernel<<<blocks, kNumThreads, (kNumThreads / 32) * partition.key_slices * sizeof(float), stream>>>(
            begin, count, output.size(2), output.size(1), output.size(3), lse_rows, output.numel(), rows,
            partition.key_slices, partial_output.const_data_ptr<float>(), partial_lse.const_data_ptr<float>(),
            output.data_ptr<float>(), lse.numel() ? lse.data_ptr<float>() : nullptr);
        C10_CUDA_KERNEL_LAUNCH_CHECK();
    });
}

__global__ void attention_delta_kernel(int64_t num_rows,
                                       int64_t channels,
                                       const float* grad,
                                       const float* output,
                                       StridedOffsetCalculator<2> offsets,
                                       float* delta)
{
    const int lane = threadIdx.x % 32;
    for (int64_t row = int64_t(blockIdx.x) * (blockDim.x / 32) + threadIdx.x / 32; row < num_rows;
         row += int64_t(gridDim.x) * (blockDim.x / 32))
    {
        const auto bases = offsets.get(row);
        float sum = 0.0f;
        for (int64_t channel = lane; channel < channels; channel += 32)
            sum += grad[bases[0] + channel] * output[bases[1] + channel];
        for (int offset = 16; offset; offset /= 2)
            sum += ::cuda::device::warp_shuffle_down(sum, offset).data;
        if (!lane)
            delta[row] = sum;
    }
}

bool supports_efficient_attention(const Tensor& query,
                                  const Tensor& key,
                                  const Tensor& value,
                                  const std::optional<Tensor>& attn_bias,
                                  double dropout_p,
                                  bool is_causal,
                                  std::optional<double> scale)
{
    if (!(dropout_p >= 0.0 && dropout_p <= 1.0) || (attn_bias.has_value() && is_causal) ||
        (scale.has_value() && !std::isfinite(*scale)))
        return false;
    for (const auto* tensor : { &query, &key, &value })
    {
        if (tensor->device().type() != kPrivateUse1 || tensor->is_nested() || tensor->layout() != kStrided ||
            tensor->dim() != 4 || tensor->scalar_type() != kFloat || !tensor->numel())
            return false;
        if (tensor->size(0) != query.size(0) || tensor->size(1) != query.size(1))
            return false;
        // CUTLASS reads aligned local buffers populated by copy_attention, which handles
        // arbitrary source strides with 64-bit indexing. Only the packed layouts need
        // unit channel strides, aligned rows and int32 head/sequence strides.
        if (tensor->size(0) > 65535 || tensor->size(1) > 65535 || tensor->size(2) > INT32_MAX - 128 ||
            tensor->size(3) > kMaxHeadDim || tensor->size(3) % 4)
            return false;
        // Sequence-major outputs and gradients also need int32 row strides.
        if (tensor->size(1) > INT32_MAX / tensor->size(3))
            return false;
    }
    if (query.size(3) != key.size(3) || key.size(2) != value.size(2))
        return false;
    if (attention_uses_rng(dropout_p))
    {
        // PyTorch 2.13 widened forward query-row RNG offsets, but batch/head
        // products in both passes remained 32-bit until 2.14. Bound the global
        // BHQK extent to the headers' index width for every GPU partition.
#if TORCH_VERSION_MAJOR > 2 || (TORCH_VERSION_MAJOR == 2 && TORCH_VERSION_MINOR >= 14)
        constexpr int64_t max_rng_elements = INT64_MAX;
#else
        constexpr int64_t max_rng_elements = INT32_MAX;
#endif
        int64_t rng_elements = 1;
        for (const auto extent : { query.size(0), query.size(1), query.size(2), key.size(2) })
        {
            if (rng_elements > max_rng_elements / extent)
                return false;
            rng_elements *= extent;
        }
    }
    if (attn_bias.has_value())
    {
        const auto& bias = *attn_bias;
        // Backend selection sees the original mask. ATen converts boolean
        // masks to additive FP32 and expands them to BHQK before execution.
        if (bias.device() != query.device() || bias.is_nested() || bias.layout() != kStrided ||
            (bias.scalar_type() != kFloat && bias.scalar_type() != kBool) || bias.dim() < 2 || bias.dim() > 4)
            return false;
        const std::array<int64_t, 4> shape{ query.size(0), query.size(1), query.size(2), key.size(2) };
        for (const auto dim : c10::irange(bias.dim()))
            if (bias.size(dim) != 1 && bias.size(dim) != shape[4 - bias.dim() + dim])
                return false;
    }
    return true;
}

bool supports_attention_devices(int64_t head_dim, bool supports_bias, bool supports_dropout)
{
    return dispatch_attention_forward(head_dim, supports_bias, supports_dropout, [](auto max_k, auto bias, auto dropout) {
        using Forward = AttentionForwardKernel<decltype(max_k)::value, decltype(bias)::value, decltype(dropout)::value>;
        using Backward = AttentionBackwardKernel<decltype(max_k)::value, decltype(dropout)::value>;
        return configure_attention_kernel<attention_forward_kernel<Forward>>(sizeof(typename Forward::SharedStorage)) &&
               configure_attention_kernel<attention_backward_kernel<Backward>>(sizeof(typename Backward::SharedStorage));
    });
}

Tensor empty_attention_tensor(const Tensor& tensor, int64_t head_dim, int64_t batches = -1)
{
    return at::empty(
               { batches < 0 ? tensor.size(0) : batches, tensor.size(2), tensor.size(1), head_dim }, tensor.options())
        .transpose(1, 2);
}

void check_attention_bias(const Tensor& bias, const Tensor& query, const Tensor& key)
{
    const std::array<int64_t, 4> shape{ query.size(0), query.size(1), query.size(2), key.size(2) };
    TORCH_CHECK(bias.scalar_type() == kFloat && bias.sizes() == IntArrayRef(shape),
                "DGX efficient attention requires an additive FP32 bias expanded to [batch, heads, queries, keys]");
}

} // namespace

int64_t fused_sdp_choice(const Tensor& query,
                         const Tensor& key,
                         const Tensor& value,
                         const std::optional<Tensor>& attn_mask,
                         double dropout_p,
                         bool is_causal,
                         std::optional<double> scale,
                         bool enable_gqa)
{
    auto& context = at::globalContext();
    for (const auto backend : context.sDPPriorityOrder())
    {
        if (backend == SDPBackend::efficient_attention && context.userEnabledMemEfficientSDP() && !enable_gqa &&
            supports_efficient_attention(query, key, value, attn_mask, dropout_p, is_causal, scale) &&
            supports_attention_devices(std::max(query.size(3), value.size(3)), attn_mask.has_value() || is_causal,
                                       attention_uses_rng(dropout_p)))
            return static_cast<int64_t>(SDPBackend::efficient_attention);
        if (backend == SDPBackend::math && context.userEnabledMathSDP())
            return static_cast<int64_t>(SDPBackend::math);
    }
    TORCH_CHECK(false,
                "No available DGX SDPA kernel: fused attention requires supported FP32 Q/K/V, an optional "
                "boolean or FP32 mask, dropout in [0, 1], and no GQA; enable the math backend for other configurations");
}

std::tuple<Tensor, Tensor, Tensor, Tensor> efficient_attention(const Tensor& query,
                                                               const Tensor& key,
                                                               const Tensor& value,
                                                               const std::optional<Tensor>& attn_bias,
                                                               bool compute_log_sumexp,
                                                               double dropout_p,
                                                               bool is_causal,
                                                               std::optional<double> scale)
{
    TORCH_CHECK(supports_efficient_attention(query, key, value, attn_bias, dropout_p, is_causal, scale) &&
                    supports_attention_devices(std::max(query.size(3), value.size(3)),
                                               attn_bias.has_value() || is_causal, attention_uses_rng(dropout_p)),
                "Unsupported DGX efficient attention configuration");
    if (attn_bias.has_value())
    {
        check_attention_bias(*attn_bias, query, key);
        // Some ATen versions request LSE only for Q/K/V gradients. A learnable
        // bias also needs it, even when all three attention inputs are frozen.
        compute_log_sumexp |= attn_bias->requires_grad();
    }
    int current_device;
    C10_CUDA_CHECK(cudaGetDevice(&current_device));
    auto restore_device = c10::make_scope_exit([&] { C10_CUDA_CHECK_WARN(cudaSetDevice(current_device)); });
    auto output = empty_attention_tensor(query, value.size(3));
    const int64_t lse_size = compute_log_sumexp ? ::cuda::ceil_div(query.size(2), int64_t{ 32 }) * 32 : 0;
    auto logsumexp = at::empty({ query.size(0), query.size(1), lse_size }, query.options());
    const bool use_dropout = attention_uses_rng(dropout_p);
    auto seed = at::zeros({}, at::TensorOptions().dtype(kLong).device(kCPU));
    auto offset = at::zeros({}, seed.options());
    uint64_t rng_seed = 0, rng_offset = 0;
    if (use_dropout)
    {
        const auto elements = attention_product(
            attention_product(query.size(0), query.size(1)), attention_product(query.size(2), key.size(2)));
        // One Philox stream covers the logical BHQK matrix, independent of
        // GPU count. Round the reservation to the DGX generator's block size.
        const uint64_t increment = (static_cast<uint64_t>(elements) + 3) / 4 * 4;
        std::tie(rng_seed, rng_offset) = at::dgx::philox_engine_inputs(std::nullopt, increment);
        *seed.data_ptr<int64_t>() = static_cast<int64_t>(rng_seed);
        *offset.data_ptr<int64_t>() = static_cast<int64_t>(rng_offset);
    }
    // The bias specialization scales scores before applying the causal mask.
    // This also keeps causal -infinity entries intact for zero/negative scales.
    const AttentionPartition partition(query, key, is_causal, dropout_p);
    const bool split_keys = partition.key_slices > 1;
    const bool local_logsumexp = compute_log_sumexp || split_keys;
    auto partial_output = split_keys ? empty_attention_tensor(query, value.size(3), partition.partials) : Tensor();
    const int64_t merge_lse_size = ::cuda::ceil_div(query.size(2), int64_t{ 32 }) * 32;
    auto partial_lse =
        split_keys ? at::empty({ partition.partials, query.size(1), merge_lse_size }, query.options()) : Tensor();
    dispatch_attention_forward(
        std::max(query.size(3), value.size(3)), attn_bias.has_value() || is_causal, use_dropout,
        [&](auto max_k, auto supports_bias, auto supports_dropout) {
            using AttentionForward = AttentionForwardKernel<decltype(max_k)::value, decltype(supports_bias)::value,
                                                            decltype(supports_dropout)::value>;
            constexpr auto shared_memory = sizeof(typename AttentionForward::SharedStorage);
            const auto kernel = configure_attention_kernel<attention_forward_kernel<AttentionForward>>(shared_memory);
            parallel_for_each([&](int device, cudaStream_t stream) {
                for (const auto& shard : partition.devices[device])
                {
                    AttentionScratch scratch(stream);
                    const AttentionBuffer q(scratch, attention_input_layout(query, shard, true, true));
                    // CUTLASS's single-query inference optimization folds broadcast
                    // heads into query rows and removes causality. Materialize key
                    // heads for masks and dropout to preserve query coordinates.
                    const bool broadcast_key_heads = local_logsumexp ||
                                                     (!use_dropout && !is_causal && !attn_bias.has_value()) ||
                                                     shard.queries % AttentionForward::kQueriesPerBlock != 1;
                    const AttentionBuffer k(scratch, attention_input_layout(key, shard, broadcast_key_heads));
                    const AttentionBuffer v(scratch, attention_input_layout(value, shard));
                    const AttentionLayout o_layout({ shard.batches, shard.heads, shard.queries, value.size(3) });
                    // Each key shard owns a contiguous partial. Write it in
                    // place instead of staging another output and LSE copy.
                    const AttentionBuffer o =
                        split_keys ? AttentionBuffer(o_layout, partial_output.data_ptr<float>() +
                                                                   shard.partial * partial_output.stride(0)) :
                                     AttentionBuffer(scratch, o_layout);
                    std::optional<AttentionBuffer> bias;
                    if (attn_bias.has_value())
                        bias.emplace(scratch, attention_bias_layout(*attn_bias, shard));
                    const int64_t local_lse_size =
                        local_logsumexp ? ::cuda::ceil_div(shard.queries, int64_t{ 32 }) * 32 : 0;
                    const int64_t lse_numel =
                        attention_product(attention_product(shard.batches, shard.heads), local_lse_size);
                    const auto lse_offset = scratch.reserve(split_keys ? 0 : lse_numel);
                    scratch.allocate();
                    q.copy_from(scratch, query, shard, stream, true);
                    k.copy_from(scratch, key, shard, stream);
                    v.copy_from(scratch, value, shard, stream);
                    typename AttentionForward::Params params;
                    if (use_dropout)
                    {
                        params.use_dropout = true;
                        params.dropout_prob = dropout_p;
                        params.rng_engine_inputs = attention_shard_rng(query, key, shard, rng_seed, rng_offset);
                    }
                    params.query_ptr = q.data(scratch);
                    params.key_ptr = k.data(scratch);
                    params.value_ptr = v.data(scratch);
                    params.output_ptr = o.data(scratch);
                    params.logsumexp_ptr = split_keys ?
                                               partial_lse.data_ptr<float>() + shard.partial * partial_lse.stride(0) :
                                               (local_logsumexp ? scratch.data(lse_offset) : nullptr);
                    params.scale = scale.value_or(1.0 / std::sqrt(double(query.size(3))));
                    params.head_dim = query.size(3);
                    params.head_dim_value = value.size(3);
                    params.num_queries = shard.queries;
                    params.num_keys = shard.keys;
                    params.num_keys_absolute = shard.keys;
                    params.num_batches = shard.batches;
                    params.num_heads = shard.heads;
                    params.custom_mask_type =
                        is_causal ? AttentionForward::CausalFromTopLeft : AttentionForward::NoCustomMask;
                    if (bias)
                    {
                        bias->copy_from(scratch, *attn_bias, shard, stream, true, true);
                        params.attn_bias_ptr = bias->data(scratch);
                        params.bias_strideB = bias->layout.strides[0];
                        params.bias_strideH = bias->layout.strides[1];
                        params.bias_strideM = bias->layout.strides[2];
                    }
                    params.q_strideB = q.layout.strides[0];
                    params.q_strideH = q.layout.strides[1];
                    params.q_strideM = q.layout.strides[2];
                    params.k_strideB = k.layout.strides[0];
                    params.k_strideH = k.layout.strides[1];
                    params.k_strideM = k.layout.strides[2];
                    params.v_strideB = v.layout.strides[0];
                    params.v_strideH = v.layout.strides[1];
                    params.v_strideM = v.layout.strides[2];
                    params.o_strideM = o.layout.strides[2];
                    AttentionForward::check_supported(params);
                    kernel<<<params.getBlocksGrid(), params.getThreadsGrid(), shared_memory, stream>>>(
                        params, query.size(2));
                    C10_CUDA_KERNEL_LAUNCH_CHECK();
                    if (split_keys)
                    {
                        if (bias)
                        {
                            const std::array<int64_t, 3> sizes{ shard.batches, shard.heads, shard.queries };
                            const std::array<int64_t, 3> lse_strides{ shard.heads * local_lse_size, local_lse_size, 1 };
                            const auto offsets = make_strided_offset_calculator<2>(
                                sizes, std::array<IntArrayRef, 2>{ IntArrayRef(bias->layout.strides).slice(0, 3),
                                                                   lse_strides });
                            const int64_t rows = shard.batches * shard.heads * shard.queries;
                            const auto blocks = static_cast<unsigned int>(
                                std::min<int64_t>(::cuda::ceil_div(rows, int64_t{ kNumThreads / 32 }), 65535));
                            attention_mask_lse_kernel<<<blocks, kNumThreads, 0, stream>>>(
                                rows, shard.keys, bias->data(scratch), params.logsumexp_ptr, offsets);
                            C10_CUDA_KERNEL_LAUNCH_CHECK();
                        }
                    }
                    else
                    {
                        o.copy_to(scratch, output, shard, stream, true);
                        if (compute_log_sumexp)
                            copy_attention_lse(params.logsumexp_ptr, logsumexp, shard, local_lse_size, true, stream);
                    }
                }
            });
        });
    if (split_keys)
        merge_attention_partials(partition, partial_output, partial_lse, output, logsumexp);
    if (static_cast<float>(dropout_p) == 1.0f)
        output.zero_();
    return { output, logsumexp, seed, offset };
}

std::tuple<Tensor, Tensor, Tensor, Tensor> efficient_attention_backward(const Tensor& grad_output,
                                                                        const Tensor& query,
                                                                        const Tensor& key,
                                                                        const Tensor& value,
                                                                        const Tensor& attn_bias,
                                                                        const Tensor& output,
                                                                        const Tensor& logsumexp,
                                                                        const Tensor& seed,
                                                                        const Tensor& offset,
                                                                        double dropout_p,
                                                                        std::array<bool, 4> grad_input_mask,
                                                                        bool is_causal,
                                                                        std::optional<double> scale)
{
    if (!grad_output.defined())
        return {};
    const auto bias_optional = attn_bias.defined() ? std::make_optional(attn_bias) : std::nullopt;
    TORCH_CHECK((attn_bias.defined() || !grad_input_mask[3]) &&
                    supports_efficient_attention(query, key, value, bias_optional, dropout_p, is_causal, scale) &&
                    supports_attention_devices(std::max(query.size(3), value.size(3)), attn_bias.defined() || is_causal,
                                               attention_uses_rng(dropout_p)),
                "Unsupported DGX efficient attention backward configuration");
    if (attn_bias.defined())
        check_attention_bias(attn_bias, query, key);
    const std::array<int64_t, 4> output_shape{ query.size(0), query.size(1), query.size(2), value.size(3) };
    TORCH_CHECK(output.device() == query.device() && output.scalar_type() == kFloat &&
                    output.sizes() == IntArrayRef(output_shape) && output.transpose(1, 2).is_contiguous(),
                "DGX efficient attention backward requires the saved BSHD output");
    TORCH_CHECK(grad_output.device() == query.device() && grad_output.scalar_type() == kFloat &&
                    grad_output.sizes() == output.sizes(),
                "DGX efficient attention backward requires a matching output gradient");
    const std::array<int64_t, 3> lse_shape{ query.size(0), query.size(1),
                                            ::cuda::ceil_div(query.size(2), int64_t{ 32 }) * 32 };
    TORCH_CHECK(logsumexp.device() == query.device() && logsumexp.scalar_type() == kFloat &&
                    logsumexp.sizes() == IntArrayRef(lse_shape) && logsumexp.is_contiguous(),
                "DGX efficient attention backward requires the saved logsumexp");
    int current_device;
    C10_CUDA_CHECK(cudaGetDevice(&current_device));
    auto restore_device = c10::make_scope_exit([&] { C10_CUDA_CHECK_WARN(cudaSetDevice(current_device)); });
    auto grad_query = grad_input_mask[0] ? empty_attention_tensor(query, query.size(3)) : Tensor();
    auto grad_key = grad_input_mask[1] ? empty_attention_tensor(key, key.size(3)) : Tensor();
    auto grad_value = grad_input_mask[2] ? empty_attention_tensor(value, value.size(3)) : Tensor();
    auto grad_bias = grad_input_mask[3] ? at::empty(attn_bias.sizes(), attn_bias.options()) : Tensor();
    if (static_cast<float>(dropout_p) == 1.0f)
    {
        return { grad_input_mask[0] ? grad_query.zero_() : Tensor(), grad_input_mask[1] ? grad_key.zero_() : Tensor(),
                 grad_input_mask[2] ? grad_value.zero_() : Tensor(), grad_input_mask[3] ? grad_bias.zero_() : Tensor() };
    }
    const bool use_dropout = attention_uses_rng(dropout_p);
    uint64_t rng_seed = 0, rng_offset = 0;
    if (use_dropout)
    {
        for (const auto* state : { &seed, &offset })
            TORCH_CHECK(state->defined() && state->device().is_cpu() && state->scalar_type() == kLong && state->dim() == 0,
                        "DGX efficient attention backward requires saved CPU int64 seed and offset scalars");
        rng_seed = static_cast<uint64_t>(seed.item<int64_t>());
        rng_offset = static_cast<uint64_t>(offset.item<int64_t>());
    }
    const AttentionPartition partition(query, key, is_causal, dropout_p);
    const bool split_keys = partition.key_slices > 1;
    const bool reduce_query = split_keys && grad_input_mask[0];
    const auto padded_query = reduce_query ? nccl_reduce_scatter_padded_numel(grad_query.numel(), query.size(3)) : 0;
    std::vector<float*> query_partials(partition.devices.size(), nullptr);
    std::vector<void*> retained_scratch(partition.devices.size(), nullptr);
    auto release_partials = c10::make_scope_exit([&] {
        if (reduce_query)
            parallel_for_each_async([&](int device, cudaStream_t stream) {
                if (retained_scratch[device])
                    C10_CUDA_CHECK_WARN(cudaFreeAsync(retained_scratch[device], stream));
            });
    });
    if (reduce_query)
        at::globalContext().lazyInitDevice(c10::DeviceType::CUDA);
    auto partial_key = partition.query_slices > 1 && grad_input_mask[1] ?
                           empty_attention_tensor(key, key.size(3), partition.partials) :
                           Tensor();
    auto partial_value = partition.query_slices > 1 && grad_input_mask[2] ?
                             empty_attention_tensor(value, value.size(3), partition.partials) :
                             Tensor();
    dispatch_attention_dropout(std::max(query.size(3), value.size(3)), use_dropout, [&](auto max_k, auto supports_dropout) {
        using AttentionBackward = AttentionBackwardKernel<decltype(max_k)::value, decltype(supports_dropout)::value>;
        static_assert(!AttentionBackward::kKernelComputesDelta);
        constexpr auto shared_memory = sizeof(typename AttentionBackward::SharedStorage);
        const auto kernel = configure_attention_kernel<attention_backward_kernel<AttentionBackward>>(shared_memory);
        parallel_for_each_async([&](int device, cudaStream_t stream) {
            if (reduce_query && partition.devices[device].empty())
            {
                // GPUs without a key shard still participate in NCCL.
                C10_CUDA_CHECK(
                    cudaMallocAsync(&retained_scratch[device], attention_product(padded_query, sizeof(float)), stream));
                query_partials[device] = static_cast<float*>(retained_scratch[device]);
                C10_CUDA_CHECK(
                    cudaMemsetAsync(query_partials[device], 0, attention_product(padded_query, sizeof(float)), stream));
            }
            for (const auto& shard : partition.devices[device])
            {
                AttentionScratch scratch(stream);
                const AttentionBuffer q(scratch, attention_input_layout(query, shard, true, true));
                const AttentionBuffer k(scratch, attention_input_layout(key, shard));
                const AttentionBuffer v(scratch, attention_input_layout(value, shard));
                const AttentionLayout o_layout({ shard.batches, shard.heads, shard.queries, value.size(3) });
                const auto* saved_output = output.const_data_ptr<float>() + shard.offset(output, true);
                // FP32 CUTLASS consumes our precomputed delta. Only that
                // one-pass dot product needs O, so it can read managed O directly.
                // Preserve support for unaligned saved-output views in the
                // direct backward operator, whose CUTLASS checks require alignment.
                std::optional<AttentionBuffer> unaligned_output;
                if (reinterpret_cast<uintptr_t>(saved_output) % (AttentionBackward::kMinimumAlignment * sizeof(float)))
                    unaligned_output.emplace(scratch, o_layout);
                const AttentionBuffer grad(scratch, attention_input_layout(grad_output, shard, true, true));
                const AttentionLayout gq_layout({ shard.batches, shard.heads, shard.queries, query.size(3) });
                const AttentionBuffer gq(scratch, gq_layout, padded_query);
                const AttentionBuffer gk(
                    scratch, AttentionLayout({ shard.batches, shard.heads, shard.keys, key.size(3) }));
                const AttentionBuffer gv(
                    scratch, AttentionLayout({ shard.batches, shard.heads, shard.keys, value.size(3) }));
                std::optional<AttentionBuffer> bias, gb;
                if (attn_bias.defined())
                    bias.emplace(scratch, attention_bias_layout(attn_bias, shard));
                if (grad_input_mask[3])
                    gb.emplace(
                        scratch, AttentionLayout({ shard.batches, shard.heads, shard.queries, shard.keys }, true, 4));
                typename AttentionBackward::Params params;
                if (use_dropout)
                {
                    params.dropout_prob = dropout_p;
                    params.rng_engine_inputs = attention_shard_rng(query, key, shard, rng_seed, rng_offset);
                }
                params.scale = scale.value_or(1.0 / std::sqrt(double(query.size(3))));
                params.head_dim = query.size(3);
                params.head_dim_value = value.size(3);
                params.num_queries = shard.queries;
                params.num_keys = shard.keys;
                params.num_batches = shard.batches;
                params.num_heads = shard.heads;
                params.custom_mask_type =
                    is_causal ? AttentionBackward::CausalFromTopLeft : AttentionBackward::NoCustomMask;
                // Use up to 256 key splits per head to expose enough GPU parallelism.
                // Each shard and its Q-gradient workspace belong to one GPU.
                if (!at::globalContext().deterministicAlgorithms())
                    params.num_splits_key =
                        std::min<int64_t>(::cuda::ceil_div(shard.keys, int64_t{ AttentionBackward::kBlockSizeJ }), 256);
                params.q_strideB = q.layout.strides[0];
                params.q_strideH = q.layout.strides[1];
                params.q_strideM = q.layout.strides[2];
                params.k_strideB = k.layout.strides[0];
                params.k_strideH = k.layout.strides[1];
                params.k_strideM = k.layout.strides[2];
                params.v_strideB = v.layout.strides[0];
                params.v_strideH = v.layout.strides[1];
                params.v_strideM = v.layout.strides[2];
                params.o_strideB = unaligned_output ? o_layout.strides[0] : output.stride(0);
                params.o_strideH = unaligned_output ? o_layout.strides[1] : output.stride(1);
                params.lse_strideB = logsumexp.stride(0);
                params.lse_strideH = logsumexp.stride(1);
                params.gO_strideB = grad.layout.strides[0];
                params.gO_strideH = grad.layout.strides[1];
                params.gO_strideM = grad.layout.strides[2];
                params.gQ_strideB = gq_layout.strides[0];
                params.gQ_strideH = gq_layout.strides[1];
                params.gK_strideB = gk.layout.strides[0];
                params.gK_strideH = gk.layout.strides[1];
                params.gV_strideB = gv.layout.strides[0];
                params.gV_strideH = gv.layout.strides[1];
                params.delta_strideB = shard.heads * shard.queries;
                params.delta_strideH = shard.queries;
                const int64_t rows = attention_product(shard.batches, params.delta_strideB);
                const auto delta_offset = scratch.reserve(rows);
                const auto workspace_numel =
                    attention_product(attention_product(shard.batches, shard.heads), params.workspace_strideBH());
                const auto workspace_bytes = attention_product(workspace_numel, sizeof(float));
                const auto workspace_offset = scratch.reserve(workspace_numel);
                scratch.allocate();
                params.query_ptr = q.data(scratch);
                params.key_ptr = k.data(scratch);
                params.value_ptr = v.data(scratch);
                params.output_ptr = unaligned_output ? unaligned_output->data(scratch) : saved_output;
                params.grad_output_ptr = grad.data(scratch);
                params.logsumexp_ptr = logsumexp.const_data_ptr<float>() + shard.offset(logsumexp, true);
                params.grad_query_ptr = gq.data(scratch);
                params.grad_key_ptr = gk.data(scratch);
                params.grad_value_ptr = gv.data(scratch);
                params.delta_ptr = scratch.data(delta_offset);
                params.workspace = workspace_bytes ? scratch.data(workspace_offset) : nullptr;
                if (bias)
                {
                    bias->copy_from(scratch, attn_bias, shard, stream, true, true);
                    params.bias_ptr = bias->data(scratch);
                    params.bias_strideB = bias->layout.strides[0];
                    params.bias_strideH = bias->layout.strides[1];
                    params.bias_strideM = bias->layout.strides[2];
                }
                if (gb)
                {
                    params.grad_bias_ptr = gb->data(scratch);
                    params.gB_strideB = gb->layout.strides[0];
                    params.gB_strideH = gb->layout.strides[1];
                    params.gB_strideM = gb->layout.strides[2];
                }
                q.copy_from(scratch, query, shard, stream, true);
                k.copy_from(scratch, key, shard, stream);
                v.copy_from(scratch, value, shard, stream);
                if (unaligned_output)
                    unaligned_output->copy_from(scratch, output, shard, stream, true);
                grad.copy_from(scratch, grad_output, shard, stream, true);
                if (reduce_query)
                {
                    query_partials[device] = gq.data(scratch);
                    if (padded_query > grad_query.numel())
                        C10_CUDA_CHECK(cudaMemsetAsync(
                            query_partials[device] + grad_query.numel(), 0,
                            attention_product(padded_query - grad_query.numel(), sizeof(float)), stream));
                }
                if (workspace_bytes && params.should_zero_workspace())
                    C10_CUDA_CHECK(cudaMemsetAsync(params.workspace, 0, workspace_bytes, stream));
                const auto blocks =
                    static_cast<unsigned int>(std::min<int64_t>(::cuda::ceil_div(rows, int64_t{ 4 }), INT32_MAX));
                const auto delta_offsets = make_strided_offset_calculator<2>(
                    IntArrayRef(o_layout.sizes).slice(0, 3),
                    std::array<IntArrayRef, 2>{ IntArrayRef(grad.layout.strides).slice(0, 3),
                                                output.strides().slice(0, 3) });
                attention_delta_kernel<<<blocks, 128, 0, stream>>>(
                    rows, value.size(3), grad.data(scratch), saved_output, delta_offsets, params.delta_ptr);
                C10_CUDA_KERNEL_LAUNCH_CHECK();
                AttentionBackward::check_supported(params);
                kernel<<<params.getBlocksGrid(), params.getThreadsGrid(), shared_memory, stream>>>(params, query.size(2));
                C10_CUDA_KERNEL_LAUNCH_CHECK();
                const AttentionShard partial_shard{
                    shard.partial, shard.batches, shard.head_begin, shard.heads, 0, shard.queries, 0, shard.keys
                };
                if (grad_input_mask[0] && !reduce_query)
                    gq.copy_to(scratch, grad_query, shard, stream, true);
                if (grad_input_mask[1])
                    gk.copy_to(scratch, partial_key.defined() ? partial_key : grad_key,
                               partial_key.defined() ? partial_shard : shard, stream);
                if (grad_input_mask[2])
                    gv.copy_to(scratch, partial_value.defined() ? partial_value : grad_value,
                               partial_value.defined() ? partial_shard : shard, stream);
                if (gb)
                    gb->copy_to(scratch, grad_bias, shard, stream, true, true);
                if (reduce_query)
                    retained_scratch[device] = scratch.release();
            }
        });
    });
    if (reduce_query)
        nccl_reduce_scatter_partials(query_partials, grad_query.data_ptr<float>(), grad_query.numel(), query.size(3));
    merge_streams();
    reduce_attention_partials(partition, partial_key, grad_key);
    reduce_attention_partials(partition, partial_value, grad_value);
    if (partial_key.defined() || partial_value.defined())
        merge_streams();
    return { grad_input_mask[0] ? grad_query : Tensor(), grad_input_mask[1] ? grad_key : Tensor(),
             grad_input_mask[2] ? grad_value : Tensor(), grad_bias };
}

